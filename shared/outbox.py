"""
Outbox pattern — SQLAlchemy model factory.

Usage:
    from sqlalchemy.orm import DeclarativeBase

    class Base(DeclarativeBase):
        pass

    OutboxEvent = make_outbox_model(Base)

The returned OutboxEvent class maps to the `outbox_events` table and can be
imported by any service that shares the same SQLAlchemy Base.
"""
import enum
import uuid
from datetime import datetime
from typing import Type

from sqlalchemy import (
    Column,
    DateTime,
    Enum,
    Integer,
    String,
    Text,
    event,
    func,
)
from sqlalchemy.orm import DeclarativeBase


class OutboxStatus(str, enum.Enum):
    PENDING = "PENDING"
    PUBLISHED = "PUBLISHED"
    FAILED = "FAILED"


def make_outbox_model(Base: Type[DeclarativeBase]):
    """
    Factory that returns an OutboxEvent SQLAlchemy ORM model bound to *Base*.

    Columns
    -------
    id              — surrogate integer primary key (auto-increment)
    event_id        — UUID string; unique, generated by default
    aggregate_type  — e.g. "WorkOrder", "Provider"
    aggregate_id    — UUID of the aggregate root
    event_type      — e.g. "work_order.created"
    payload         — JSON-serialised event payload (Text)
    version         — optimistic-locking / event-sequence counter
    trace_id        — X-Correlation-ID for distributed tracing
    status          — PENDING | PUBLISHED | FAILED
    created_at      — set on INSERT
    updated_at      — updated on every change
    """

    class OutboxEvent(Base):  # type: ignore[valid-type]
        __tablename__ = "outbox_events"

        id: int = Column(Integer, primary_key=True, autoincrement=True)
        event_id: str = Column(
            String(36),
            unique=True,
            nullable=False,
            default=lambda: str(uuid.uuid4()),
        )
        aggregate_type: str = Column(String(128), nullable=False, index=True)
        aggregate_id: str = Column(String(36), nullable=False, index=True)
        event_type: str = Column(String(128), nullable=False, index=True)
        payload: str = Column(Text, nullable=False)
        version: int = Column(Integer, nullable=False, default=1)
        trace_id: str = Column(String(36), nullable=True)
        status: OutboxStatus = Column(
            Enum(OutboxStatus, native_enum=False),
            nullable=False,
            default=OutboxStatus.PENDING,
            index=True,
        )
        created_at: datetime = Column(
            DateTime,
            nullable=False,
            default=datetime.utcnow,
            server_default=func.now(),
        )
        updated_at: datetime = Column(
            DateTime,
            nullable=False,
            default=datetime.utcnow,
            onupdate=datetime.utcnow,
            server_default=func.now(),
        )

        def __repr__(self) -> str:
            return (
                f"<OutboxEvent id={self.id} event_type={self.event_type!r} "
                f"status={self.status} aggregate_id={self.aggregate_id!r}>"
            )

    return OutboxEvent
