from typing import List, Optional
import uuid
from fastapi import APIRouter, Depends, Query, status
from sqlalchemy.orm import Session

from app.database import get_db
from app.repository import NotificationRepository
from app.service import NotificationService
from app.schemas import NotificationLogResponse, NotificationCreateRequest

router = APIRouter(prefix="/api/v1/notifications", tags=["notifications"])


def get_service(db: Session = Depends(get_db)) -> NotificationService:
    repo = NotificationRepository(db)
    return NotificationService(repo, db)


@router.get(
    "/logs",
    response_model=List[NotificationLogResponse],
    summary="List all dispatched notification logs",
)
def list_logs(
    limit: int = Query(100, ge=1, le=500),
    offset: int = Query(0, ge=0),
    service: NotificationService = Depends(get_service),
):
    return service.list_logs(limit=limit, offset=offset)


@router.get(
    "/events/{event_id}",
    response_model=List[NotificationLogResponse],
    summary="Get notification logs generated by a specific event ID",
)
def get_logs_by_event(
    event_id: str,
    service: NotificationService = Depends(get_service),
):
    return service.get_logs_for_event(event_id)


@router.post(
    "/send",
    response_model=NotificationLogResponse,
    status_code=status.HTTP_201_CREATED,
    summary="Send a direct notification (simulated)",
)
def send_notification(
    payload: NotificationCreateRequest,
    service: NotificationService = Depends(get_service),
):
    log = service.dispatch_notification(
        event_id=str(uuid.uuid4()),
        event_type="ManualNotification",
        recipient=payload.recipient,
        channel=payload.channel,
        message=payload.message,
        subject=payload.subject,
    )
    service.db.commit()
    return NotificationLogResponse.model_validate(log)
